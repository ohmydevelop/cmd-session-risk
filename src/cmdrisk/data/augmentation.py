"""Deterministic, provenance-preserving stress augmentation.

The first corpus has no teacher-model credentials and must not imply that
synthetic rows were generated by an LLM.  This module therefore creates
labelled stress examples with explicit deterministic transformations.  Every
derived record keeps a parent session link and a family id, allowing the split
audit to keep the original lineage and its variants together.
"""

from __future__ import annotations

import hashlib
import shlex
from collections.abc import Iterable
from typing import Any

from cmdrisk.schema import (
    CommandEvent,
    Label,
    LabelQuality,
    SessionRecord,
    SourceInfo,
    SourceKind,
)

from .normalization import clean_command, stable_session_id

AUGMENTATION_METHOD = "deterministic"
AUGMENTATION_VERSION = "v1"

_ATTACK_VARIANT_NAMES = (
    "shell-split",
    "tool-alias",
    "path-variation",
    "argument-variation",
)

_HARD_NEGATIVE_TEMPLATES: tuple[tuple[str, tuple[str, ...]], ...] = (
    (
        "source-install",
        (
            "mkdir -p /tmp/app-build",
            "curl -fsSL https://example.com/releases/app.tar.gz -o /tmp/app.tar.gz",
            "tar -xzf /tmp/app.tar.gz -C /tmp/app-build",
            "chmod +x /tmp/app-build/install.sh",
            "/tmp/app-build/install.sh --prefix /usr/local",
        ),
    ),
    (
        "ci-build",
        (
            "git clone https://github.com/example/project.git /tmp/project",
            "cd /tmp/project",
            "make",
            "make test",
            "make install",
        ),
    ),
    (
        "python-package",
        (
            "python -m pip install --user -r requirements.txt",
            "python -m pytest -q",
            "python -m pip install --user ./dist/app.whl",
        ),
    ),
    (
        "container-build",
        (
            "docker build -t example/app:local .",
            "docker run --rm example/app:local --version",
            "docker image prune -f",
        ),
    ),
    (
        "apt-install",
        (
            "apt-get update",
            "apt-get install -y curl ca-certificates",
            "curl -fsSL https://example.com/tool.tar.gz | tar -xz -C /usr/local/bin",
            "chmod +x /usr/local/bin/tool",
        ),
    ),
    (
        "release-bundle",
        (
            "wget -q https://example.com/bundle.zip -O /tmp/bundle.zip",
            "unzip -q /tmp/bundle.zip -d /opt/bundle",
            "chmod 755 /opt/bundle/start.sh",
            "/opt/bundle/start.sh --health-check",
        ),
    ),
)


def _rank(value: str, seed: int) -> str:
    return hashlib.sha256(f"{seed}\x1f{value}".encode()).hexdigest()


def _record_text(record: SessionRecord) -> list[str]:
    return [clean_command(event.cmd) for event in record.commands if clean_command(event.cmd)]


def _mutation_variant(commands: list[str], variant_index: int) -> list[str]:
    """Return a deterministic attack-like variant without changing intent."""

    mutations: list[str] = []
    for command in commands[:64]:
        value = command
        if "whoami" in value.casefold():
            value = value.replace("whoami", "id -un")
        if "uname -a" in value:
            value = value.replace("uname -a", "uname -mrs")
        if "chmod +x" in value:
            value = value.replace("chmod +x", "chmod 755")
        if "base64 -d" in value:
            value = value.replace("base64 -d", "base64 --decode")
        if value.startswith("wget "):
            value = "curl -fsSL " + value[5:]
        if value.startswith("curl "):
            value = value.replace("curl ", "curl -fsSL ", 1)
        if "/tmp/" in value:
            value = value.replace("/tmp/", "/var/tmp/")
        mutations.append(clean_command(value))

    if not mutations:
        mutations = ["id -un"]

    # A shell wrapper is a realistic execution variation and also exercises
    # tokenisation across quoting boundaries.
    if variant_index % 4 == 0 and len(mutations) > 1:
        index = min(1, len(mutations) - 1)
        mutations[index] = f"sh -c {shlex.quote(mutations[index])}"
    elif variant_index % 4 == 1 and mutations:
        mutations[0] = f"sh -c {shlex.quote(mutations[0])}"
    elif variant_index % 4 == 2:
        mutations.insert(0, "export TMPDIR=/var/tmp")
    else:
        mutations.append("echo command-sequence-check")

    # Keep deterministic uniqueness even when a source session needs no tool
    # replacement; this is metadata-neutral for the attack semantics.
    return [clean_command(command) for command in mutations if clean_command(command)]


def _inherited_attack_label(base: SessionRecord) -> Label:
    techniques = list(base.label.techniques)
    tactics = list(base.label.tactics)
    evidence = {technique: [0] for technique in techniques}
    return Label(
        malicious=1,
        first_evidence_index=0,
        technique_evidence=evidence,
        tactics=tactics,
        techniques=techniques,
        quality=LabelQuality.HIGH,
    )


def _hard_negative_commands(
    base: SessionRecord,
    *,
    variant_index: int,
) -> tuple[str, list[str]]:
    """Blend a benign source session with a realistic DevOps install flow."""

    template_name, template = _HARD_NEGATIVE_TEMPLATES[
        variant_index % len(_HARD_NEGATIVE_TEMPLATES)
    ]
    base_commands = _record_text(base)[:16]
    # Keep only a recognizable benign prefix; the template supplies the
    # download/chmod/execute look-alike behavior that should not be malicious.
    return template_name, [*base_commands, *template]


def _derived_record(
    *,
    base: SessionRecord,
    commands: list[str],
    source_kind: SourceKind,
    source_name: str,
    variant_index: int,
    method: str,
    template: str | None = None,
) -> SessionRecord:
    external_id = f"{base.session_id}:{source_kind.value}:{variant_index}"
    session_id = stable_session_id(source_name, commands, external_id=external_id)
    meta: dict[str, Any] = {
        "raw_commands": list(commands),
        "augmentation_method": AUGMENTATION_METHOD,
        "augmentation_version": AUGMENTATION_VERSION,
        "augmentation_family": method,
        "base_session_id": base.session_id,
        "base_source_kind": str(base.source.kind),
        "base_source_name": base.source.name,
        "variant_index": variant_index,
        "evaluation_slice": "synthetic_stress",
    }
    if template is not None:
        meta["hard_negative_template"] = template
    return SessionRecord(
        session_id=session_id,
        source=SourceInfo(
            kind=source_kind,
            name=source_name,
            parent_session_id=base.session_id,
            license=base.source.license,
        ),
        family_id=base.family_id,
        commands=[CommandEvent(cmd=command) for command in commands],
        meta=meta,
        label=(
            _inherited_attack_label(base)
            if source_kind == SourceKind.LLM_VARIANT
            else Label(malicious=0, quality=LabelQuality.HIGH)
        ),
    )


def generate_deterministic_stress(
    records: Iterable[SessionRecord],
    *,
    malicious_count: int,
    hard_negative_count: int,
    seed: int = 42,
) -> list[SessionRecord]:
    """Generate exact deterministic positive variants and hard negatives.

    The function intentionally uses ``SourceKind.LLM_VARIANT`` for compatibility
    with the training vocabulary, but all records carry
    ``meta["augmentation_method"] == "deterministic"``.  They must never be
    reported as teacher/LLM-generated data.
    """

    if malicious_count < 0 or hard_negative_count < 0:
        raise ValueError("augmentation counts must be non-negative")
    values = list(records)
    malicious_bases = sorted(
        (
            record
            for record in values
            if record.source.kind == SourceKind.REAL_MALICIOUS
            and not _looks_like_atomic_seed(record)
        ),
        key=lambda record: _rank(record.session_id, seed),
    )
    benign_bases = sorted(
        (
            record
            for record in values
            if record.source.kind in {SourceKind.REAL_BENIGN, SourceKind.SCRIPT_BENIGN}
        ),
        key=lambda record: _rank(record.session_id, seed + 1),
    )
    if malicious_count and not malicious_bases:
        raise ValueError("cannot generate deterministic attack variants without malicious bases")
    if hard_negative_count and not benign_bases:
        raise ValueError("cannot generate deterministic hard negatives without benign bases")

    # Every derived row receives a globally unique ``variant_index`` so its
    # session id cannot collide, while the *style* index cycles over the
    # available transformations so a run uses all of them.
    style_count = len(_ATTACK_VARIANT_NAMES)
    if malicious_count > len(malicious_bases) * style_count:
        raise ValueError(
            "cannot generate unique deterministic attack variants: "
            f"{malicious_count} requested > {len(malicious_bases)} bases x {style_count} styles"
        )
    template_count = len(_HARD_NEGATIVE_TEMPLATES)
    if hard_negative_count > len(benign_bases) * template_count:
        raise ValueError(
            "cannot generate unique deterministic hard negatives: "
            f"{hard_negative_count} requested > {len(benign_bases)} bases x {template_count}"
        )

    generated: list[SessionRecord] = []
    for index in range(malicious_count):
        base = malicious_bases[index % len(malicious_bases)]
        style_index = index % style_count
        commands = _mutation_variant(_record_text(base), style_index)
        generated.append(
            _derived_record(
                base=base,
                commands=commands,
                source_kind=SourceKind.LLM_VARIANT,
                source_name="deterministic_attack_variant",
                variant_index=index,
                method=_ATTACK_VARIANT_NAMES[style_index],
            )
        )

    for index in range(hard_negative_count):
        base = benign_bases[index % len(benign_bases)]
        template, commands = _hard_negative_commands(base, variant_index=index)
        generated.append(
            _derived_record(
                base=base,
                commands=commands,
                source_kind=SourceKind.HARD_NEGATIVE,
                source_name="deterministic_hard_negative",
                variant_index=index,
                method="devops-install-lookalike",
                template=template,
            )
        )
    return generated


def _looks_like_atomic_seed(record: SessionRecord) -> bool:
    if record.source.name.casefold() in {"atomic_red_team", "atomic-red-team"}:
        return True
    return any(
        key in record.meta
        for key in ("atomic_source", "atomic_test_name", "atomic_seed", "technique_seed")
    )
